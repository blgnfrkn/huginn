const express = require('express');
const { createClient } = require('@supabase/supabase-js');
const axios = require('axios');
const nodemailer = require('nodemailer');
require('dotenv').config();

const app = express();
const port = process.env.PORT || 3000;

app.use(express.json());

const supabase = createClient(
    process.env.SUPABASE_URL,
    process.env.SUPABASE_KEY
);

const MIN_CVSS_SCORE = 0; // Test icin 0; ilk gercek bildirim sonrasi 8.0 yapilabilir
const KEEP_ALIVE_INTERVAL_MS = 4 * 24 * 60 * 60 * 1000; // 4 gun

const pingSupabaseKeepAlive = async () => {
    try {
        const { error } = await supabase
            .from('vulnerability_logs')
            .select('id')
            .limit(1);

        if (error) {
            console.error('[SUPABASE-KEEPALIVE] Ping error:', error.message);
            return;
        }
        console.log('[SUPABASE-KEEPALIVE] Database heartbeat OK.');
    } catch (error) {
        console.error('[SUPABASE-KEEPALIVE] Unexpected ping failure:', error.message);
    }
};

app.get('/', (req, res) => {
    res.status(200).send('Huginn is awake and watching!');
});

const sendTelegramNotification = async (message) => {
    const url = `https://api.telegram.org/bot${process.env.TELEGRAM_BOT_TOKEN}/sendMessage`;
    try {
        await axios.post(url, {
            chat_id: process.env.TELEGRAM_CHAT_ID,
            text: message,
            parse_mode: 'HTML'
        });
        console.log('[TELEGRAM] Notification dispatched successfully.');
    } catch (error) {
        console.error('[TELEGRAM] Error dispatching notification:', error.response ? error.response.data : error.message);
    }
};

const sendEmailNotification = async (cveData) => {
    const transporter = nodemailer.createTransport({
        service: 'gmail',
        auth: {
            user: process.env.GMAIL_USER,
            pass: process.env.GMAIL_APP_PASSWORD
        }
    });

    const mailOptions = {
        from: process.env.GMAIL_USER,
        to: process.env.GMAIL_USER,
        subject: `🚨 VULNERABILITY DETECTED: ${cveData.cve_id}`,
        html: `
            <h2>⚠️ Security Alert</h2>
            <p><strong>CVE Identifier:</strong> ${cveData.cve_id}</p>
            <p><strong>CVSS Score:</strong> ${cveData.score}</p>
            <p><strong>Vendor/Product:</strong> ${cveData.vendor_product}</p>
            <p><strong>Description:</strong> ${cveData.description}</p>
            <p><em>This alert was automatically generated by the Huginn Monitoring System.</em></p>
        `
    };

    try {
        await transporter.sendMail(mailOptions);
        console.log('[EMAIL] Notification dispatched successfully.');
    } catch (error) {
        console.error('[EMAIL] Error dispatching notification:', error.message);
    }
};

app.post('/webhook', async (req, res) => {
    try {
        const payload = req.body;
        console.log('[WEBHOOK] Received payload:', JSON.stringify(payload, null, 2));

        const rawCve = typeof payload.cve === 'object' ? payload.cve?.id : payload.cve;
        const cve_id = rawCve || payload.id || payload.data?.id;
        const score = parseFloat(payload.cvss_score ?? payload.cvss ?? payload.cve?.cvss ?? 0);
        const vendor = payload.vendor || (Array.isArray(payload.vendors) ? payload.vendors[0] : null) || 'Unknown Vendor';
        const product = payload.product || (Array.isArray(payload.products) ? payload.products[0] : null) || 'Unknown Product';
        const vendor_product = `${vendor} / ${product}`;
        const description = payload.description || payload.summary || payload.cve?.summary || 'No description provided.';

        if (!cve_id && payload.subscriptions) {
            console.log('[WEBHOOK] OpenCVE test ping received successfully.');
            return res.status(200).send('OpenCVE webhook test ping acknowledged.');
        }

        if (!cve_id) {
            console.warn('[WEBHOOK] Rejected payload: Missing CVE identifier.');
            return res.status(400).send('Bad Request: Missing CVE identifier.');
        }

        if (score < MIN_CVSS_SCORE) {
            console.log(`[FILTER] Ignored ${cve_id} (CVSS: ${score} < ${MIN_CVSS_SCORE})`);
            return res.status(200).send('Payload acknowledged but filtered (CVSS threshold not met).');
        }

        const { data: existingRecords, error: fetchError } = await supabase
            .from('vulnerability_logs')
            .select('id')
            .eq('cve_id', cve_id);

        if (fetchError) {
            console.error('[SUPABASE] Database query error:', fetchError.message);
            return res.status(500).send('Internal Server Error during database query.');
        }

        if (existingRecords && existingRecords.length > 0) {
            console.log(`[DEDUPLICATION] CVE ${cve_id} already exists in records. Discarding.`);
            return res.status(200).send('Payload acknowledged (Duplicate record).');
        }

        const { error: insertError } = await supabase
            .from('vulnerability_logs')
            .insert([{
                cve_id: cve_id,
                score: score,
                vendor_product: vendor_product,
                description: description
            }]);

        if (insertError) {
            console.error('[SUPABASE] Database insertion error:', insertError.message);
            return res.status(500).send('Internal Server Error during database insertion.');
        }
        console.log(`[SUPABASE] Successfully persisted ${cve_id} to database.`);

        const alertMessage = `🚨 <b>VULNERABILITY DETECTED</b> 🚨\n\n` +
                             `<b>CVE:</b> ${cve_id}\n` +
                             `<b>CVSS Score:</b> ${score}\n` +
                             `<b>Vendor/Product:</b> ${vendor_product}\n\n` +
                             `<b>Description:</b>\n${description}`;

        await Promise.all([
            sendTelegramNotification(alertMessage),
            sendEmailNotification({ cve_id, score, vendor_product, description })
        ]);

        res.status(200).send('Vulnerability processed and notifications dispatched successfully.');

    } catch (error) {
        console.error('[SYSTEM] Unhandled exception in webhook processing:', error);
        res.status(500).send('Internal Server Error');
    }
});

app.listen(port, () => {
    console.log(`[SYSTEM] 🦅 Huginn is operational and monitoring on port ${port}...`);
    pingSupabaseKeepAlive();
    setInterval(pingSupabaseKeepAlive, KEEP_ALIVE_INTERVAL_MS);
});